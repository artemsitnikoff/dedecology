"""Карта соответствия: код субъекта РФ (ФГИС) → фиксированное смещение UTC в часах.

В России НЕТ перехода на летнее время (с 2014) → у каждого субъекта постоянное
смещение UTC (+2..+12), поэтому целочисленной карты достаточно и она не устаревает.

Ключи — коды субъектов КАК В `Region.code` (строка с ведущим нулём для <10: "01","05",…),
та же схема, что в `region_fed.py`. «Хвост» ФГИС нумерует по-своему: 80=Ненецкий АО,
81=ХМАО-Югра, 82=Чукотский АО, 83=ЯНАО, 84=Крым, 85=Севастополь (учтено ниже).

Используется в выгрузке УТКО: время фотофиксации хранится как МЕСТНОЕ настенное время
волонтёра (services/intake._photo_wallclock, смещение отброшено, помечено UTC). Чтобы
отдать в УТКО реальный UTC, вычитаем смещение пояса РЕГИОНА инцидента (см. utko_export).
"""

# смещение UTC (часы) → список кодов субъектов ФГИС (строками, с ведущим нулём для <10).
